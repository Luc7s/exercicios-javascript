function semana(dia){
    switch (dia) {
        case "segunda":
            console.log("primeiro dia")
            break;
        case "terca":
            console.log("segundo")
            break;
        case "quarta":
            console.log("terceiro")
            break;               
        default:
            console.log("oitavo dia")
            break;
    }
}
semana()